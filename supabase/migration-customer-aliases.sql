-- Map free-text valves.customer values to canonical customers.id.
-- alias_text is stored normalized (lower(trim(...))).
-- Run once in the Supabase SQL Editor (after public.customers exists).

begin;

create table if not exists public.customer_aliases (
  id bigint generated by default as identity primary key,
  alias_text text not null,
  customer_id bigint not null references public.customers (id) on delete cascade,
  created_at timestamptz not null default now(),
  created_by_name text not null default '',
  constraint customer_aliases_alias_text_unique unique (alias_text)
);

create index if not exists idx_customer_aliases_customer_id
  on public.customer_aliases (customer_id);

comment on table public.customer_aliases is
  'Normalized lowercase/trimmed valves.customer text → canonical customers row for demand reports.';

alter table public.customer_aliases enable row level security;

drop policy if exists "authenticated read customer aliases" on public.customer_aliases;
create policy "authenticated read customer aliases"
on public.customer_aliases
for select
to authenticated
using (true);

drop policy if exists "authenticated insert customer aliases" on public.customer_aliases;
create policy "authenticated insert customer aliases"
on public.customer_aliases
for insert
to authenticated
with check (true);

drop policy if exists "authenticated update customer aliases" on public.customer_aliases;
create policy "authenticated update customer aliases"
on public.customer_aliases
for update
to authenticated
using (true)
with check (true);

drop policy if exists "authenticated delete customer aliases" on public.customer_aliases;
create policy "authenticated delete customer aliases"
on public.customer_aliases
for delete
to authenticated
using (true);

grant select, insert, update, delete on public.customer_aliases to authenticated;
grant usage, select on sequence public.customer_aliases_id_seq to authenticated;

-- Helper: normalize customer text the same way reports / admin mapping do.
create or replace function public.normalize_customer_alias_text(p_raw text)
returns text
language sql
immutable
as $$
  select nullif(lower(btrim(coalesce(p_raw, ''))), '');
$$;

commit;
