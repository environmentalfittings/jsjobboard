function cellValue(g: (key: string) => string, key: string) {
  // "Lift / RL" is two blanks on the form; a single "0.753 / 0.5" entry is split across them.
  if (key === 'lift' || key === 'lift_rl') {
    const lift = g('lift')
    if (!g('lift_rl').trim() && lift.includes('/')) {
      const [a, ...rest] = lift.split('/')
      return key === 'lift' ? a.trim() : rest.join('/').trim()
    }
  }
  return g(key).trim()
}

function drawCell(c: VkFormCell, g: (key: string) => string) {
  const raw = cellValue(g, c.k)
  switch (c.t) {
    case 'text': {
      const value = (c.d ? fmtDate(raw) : raw) || c.blank || ''
      if (!value) return ''
      const size = c.sz ?? 10
      // data-w is the cell width; the fit script in the page squeezes any value that runs past it.
      return `<text class="${c.f ?? 't'} v" x="${c.x}" y="${c.y}" font-size="${size}" data-w="${c.w}"${
        c.c ? ` style="fill:${c.c}"` : ''
      }${c.a ? ` text-anchor="${c.a}"` : ''}>${esc(value)}</text>`
    }
    case 'multi': {
      if (!raw) return ''
      const size = c.sz ?? 9
      return `<foreignObject x="${c.x}" y="${c.y}" width="${c.w}" height="${c.h}"><div xmlns="http://www.w3.org/1999/xhtml" class="mv" style="font-size:${size}px;line-height:${(size * 1.2).toFixed(1)}px;height:${c.h}px">${esc(raw)}</div></foreignObject>`
    }
    case 'box': {
      const on = c.m === 'filled' ? raw !== '' : c.m === 'eq' ? canon(raw) === canon(c.v ?? '') : isYes(raw)
      if (!on) return ''
      const p = 2
      const [x0, y0, x1, y1] = [c.x + p, c.y + p, c.x + c.s - p, c.y + c.s - p]
      return `<path class="x" d="M${x0} ${y0}L${x1} ${y1}M${x1} ${y0}L${x0} ${y1}"/>`
    }
    case 'choice': {
      if (!raw) return ''
      const sel = matchChoice(raw, c.o.map((o) => o[0]))
      if (sel < 0) {
        // A value that is not one of the printed choices is still shown so data is never lost.
        const last = c.o[c.o.length - 1]
        return `<text class="tb v" x="${last[2] + 6}" y="${c.y}" font-size="9">${esc(raw)}</text>`
      }
      const [, x0, x1] = c.o[sel]
      return `<ellipse class="o" cx="${((x0 + x1) / 2).toFixed(1)}" cy="${(c.y - 3.2).toFixed(1)}" rx="${((x1 - x0) / 2 + 2.4).toFixed(1)}" ry="5.6"/>`
    }
    case 'code': {
      const letter = codeLetter(raw)
      return letter ? `<text class="tb v" x="${c.x}" y="${c.y}" font-size="9" text-anchor="middle">${esc(letter)}</text>` : ''
    }
  }
}

function formPage(page: number, g: (key: string) => string, logoSrc: string) {
  const b = VK_FORM_LOGO_BOX
  const logo =
    page === 0
      ? `<image href="${esc(logoSrc)}" x="${b.x}" y="${b.y}" width="${b.w}" height="${b.h}" preserveAspectRatio="xMidYMid meet"/>`
      : ''
  const overlay = VK_FORM_CELLS.filter((c) => c.p === page)
    .map((c) => drawCell(c, g))
    .join('')
  return `<section class="sheet form"><svg class="fm" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 612 792" preserveAspectRatio="xMidYMid meet">${logo}${VK_FORM_ART[page]}${overlay}</svg></section>`
}

